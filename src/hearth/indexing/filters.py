"""What gets indexed, and what never does.

Ignore layers, most specific first (docs/system-design.md §6.2):

1. config ``index.exclude`` — an explicit "no"
2. config ``index.include`` — an explicit "yes", which overrides layers 3 and 4 so a
   project can deliberately index a vendored subtree
3. built-in defaults — ``.git/``, ``node_modules/``, lockfiles, minified output, media
4. ``.gitignore``, then ``.hearthignore``

Then size, binary and generated-code checks.

**Secret files are never indexed, at any layer, and no config can re-enable them.** An
``index.include`` entry cannot override the denylist: a `.env` reaching the index would
put credentials into a database, into retrieval results, and from there into a prompt.
That is a one-way mistake, so the check is an invariant rather than a default
(docs/safety-and-tool-use.md §10).
"""

